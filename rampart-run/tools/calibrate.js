/* Finds a difficulty scale k for each level and writes src/cal.js.
   kBest = the hardest scale at which the solver still finds a winning line.
   Shipped k backs off from that so a human has some slack.
   Run: node tools/calibrate.js [maxLevel] */
'use strict';
const fs = require('fs');
const path = require('path');
const R = require('../src/sim.js');
const MAX = +process.argv[2] || 60;
const GRID = [];
for (let k = 8; k > 0.2; k /= 1.12) GRID.push(+k.toFixed(2));
const out = {};
const info = [];
for (let lvl = 1; lvl <= MAX; lvl++) {
  const target = R.targetK(lvl);
  let pick = null, fallback = null;
  for (let v = 0; v < 24 && !pick; v++) {
    let best = GRID[GRID.length - 1];
    for (const k of GRID) { if (R.solve(R.genLevel(lvl, k, v))) { best = k; break; } }
    let ship = Math.min(target, best * 0.85);
    // a level that can be won by running straight needs more bite or a new layout
    let tries = 0;
    while (lvl >= 2 && R.straight(R.genLevel(lvl, ship, v)) && ship * 1.12 <= best * 0.95 && tries++ < 6) ship *= 1.12;
    ship = +ship.toFixed(2);
    const L = R.genLevel(lvl, ship, v);
    const ok = R.solve(L), st = R.straight(L);
    if (ok && (lvl < 2 || !st) && ship >= target * 0.7) pick = [ship, v, best];
    else if (ok && (lvl < 2 || !st) && !fallback) fallback = [ship, v, best];
  }
  if (!pick) pick = fallback;
  if (!pick) throw new Error('no winnable layout for level ' + lvl);
  out[lvl] = [pick[0], pick[1]];
  const L = R.genLevel(lvl, pick[0], pick[1]);
  info.push(lvl + ': k ' + pick[0] + ' v ' + pick[1] + ' target ' + target.toFixed(2) + ' solver ' + R.solve(L) + ' straight ' + R.straight(L));
}
console.log(info.join('\n'));
const body = '/* Generated by tools/calibrate.js. Do not edit by hand. */\n' +
  '(function (root) {\n  var RR = root.RR || (typeof require === "function" ? require("./sim.js") : null);\n' +
  '  RR.setCal(' + JSON.stringify(out) + ');\n})(typeof self !== "undefined" ? self : this);\n';
fs.writeFileSync(path.join(__dirname, '../src/cal.js'), body);
